import fs from "fs";
import path from "path";
import { JSDOM } from "jsdom";
import { GoogleGenAI } from "@google/genai";
import { ContextFuser } from "../src/services/context-engine/context-fuser";
import { buildContextAwarePrompt } from "../src/services/context-engine/prompt-builder";

const MOCK_HTML = `
<!DOCTYPE html>
<html>
<head><title>CRM Invoice Dashboard</title></head>
<body>
  <h1>Invoices</h1>
  <table role="table">
    <thead>
      <tr role="row">
        <th role="columnheader">ID</th>
        <th role="columnheader">Client</th>
        <th role="columnheader">Amount</th>
        <th role="columnheader">Status</th>
      </tr>
    </thead>
    <tbody>
      <tr role="row"><td>INV-001</td><td>Acme Corp</td><td>$1,500.00</td><td>Paid</td></tr>
      <tr role="row"><td>INV-002</td><td>Globex</td><td>$3,200.00</td><td>Overdue</td></tr>
      <tr role="row"><td>INV-003</td><td>Initech</td><td>$450.00</td><td>Pending</td></tr>
      <tr role="row"><td>INV-004</td><td>Soylent</td><td>$8,900.00</td><td>Paid</td></tr>
      <tr role="row"><td>INV-005</td><td>Umbrella</td><td>$12,000.00</td><td>Overdue</td></tr>
      <tr role="row" style="display:none; height: 0px; width: 0px;" id="hidden-row"><td>INV-006</td><td>Hidden</td><td>$0</td><td>Hidden</td></tr>
    </tbody>
  </table>
</body>
</html>
`;

async function runTest() {
  console.log("=== STAGE 1: BROWSER CONTEXT EXTRACTION ===");
  
  // 1. Setup JSDOM
  const dom = new JSDOM(MOCK_HTML, { url: "http://localhost/invoices", runScripts: "dangerously" });
  const window = dom.window;
  const document = window.document;

  // We need to mock some browser APIs that jsdom doesn't have perfectly
  window.IntersectionObserver = (class {
    observe() {} unobserve() {} disconnect() {}
  }) as any;
  // In JSDOM, offsetHeight is 0 by default, so we mock it for visible elements
  Object.defineProperty(window.HTMLElement.prototype, 'offsetHeight', {
    get() { return this.id === 'hidden-row' ? 0 : 20; }
  });
  Object.defineProperty(window.HTMLElement.prototype, 'offsetWidth', {
    get() { return this.id === 'hidden-row' ? 0 : 100; }
  });

  // Read the widget-context-engine.js code
  const engineCode = fs.readFileSync(path.join(process.cwd(), "../../frontend/chat-app/public/widget-context-engine.js"), "utf-8");
  
  // Inject and execute the engine
  const scriptEl = document.createElement("script");
  scriptEl.textContent = engineCode;
  document.head.appendChild(scriptEl);

  // Use the Enterprise Window.AriaContext API to bypass JSDOM rendering limits
  window.AriaContext = {
    page: "table",
    tables: [{
      headers: ["ID", "Client", "Amount", "Status"],
      rows: [
        ["INV-001", "Acme Corp", "$1,500.00", "Paid"],
        ["INV-002", "Globex", "$3,200.00", "Overdue"],
        ["INV-003", "Initech", "$450.00", "Pending"],
        ["INV-004", "Soylent", "$8,900.00", "Paid"],
        ["INV-005", "Umbrella", "$12,000.00", "Overdue"]
      ],
      rowCount: 5
    }]
  } as any;

  // Run extraction
  const AriaContextEngine = (window as any).AriaContextEngine;
  const engine = new AriaContextEngine({ mutationThreshold: 10 });
  engine.start(document.body);
  const websiteContext = await engine.getContext();
  
  console.log("-> Exact websiteContext JSON generated by the browser:");
  console.log(JSON.stringify(websiteContext || { error: "Context was null" }, null, 2));

  console.log("\n=== STAGE 2: NETWORK REQUEST ===");
  const chatHistory = [{ role: "user", content: "How many invoices are visible?" }];
  const requestBody = {
    messages: chatHistory,
    websiteContext: websiteContext || {},
    sessionId: "mock-session-123"
  };
  console.log("-> Exact JSON sent in the POST request:");
  console.log(JSON.stringify(requestBody, null, 2));

  console.log("\n=== STAGE 3: BACKEND RECEPTION ===");
  // (In a real Express app this is just req.body.websiteContext)
  const receivedWebsiteContext = requestBody.websiteContext;
  console.log("-> Exact req.body.websiteContext:");
  console.log(JSON.stringify(receivedWebsiteContext, null, 2));

  console.log("\n=== STAGE 4: CONTEXT FUSION ===");
  const contextFuser = new ContextFuser();
  
  // Pass the real API key to let the Intent Classifier work
  const apiKey = process.env.AI_INTEGRATIONS_GEMINI_API_KEY;
  if (!apiKey) throw new Error("Missing AI_INTEGRATIONS_GEMINI_API_KEY");

  const fusedContext = await contextFuser.fuse({
    userMessage: chatHistory[0].content,
    websiteContext: receivedWebsiteContext,
    projectId: "11111111-1111-1111-1111-111111111111",
    userId: null,
    settings: {
      enabled: true,
      mistakeDetection: false,
      contextMemory: false,
      maxContextSizeBytes: 500000,
      piiRedaction: true,
      tableAnalysis: true,
      dashboardAnalysis: true,
      formAssistant: true,
      navigationAssistant: true
    },
    apiKeys: [{ decryptedKey: apiKey }]
  });

  console.log("-> Intent Classified As:", fusedContext.userIntent);
  console.log("-> Fused Context String before Prompt Builder:");
  console.log(fusedContext.websiteContextString);

  console.log("\n=== STAGE 5: PROMPT BUILDER ===");
  const systemPrompt = buildContextAwarePrompt({
    project: { systemPrompt: "I am a test assistant." },
    fusedContext,
    settings: { enabled: true, mistakeDetection: false, contextMemory: false, maxContextSizeBytes: 500000, piiRedaction: true }
  });

  console.log("-> Section of the final prompt containing the invoice data:");
  console.log(systemPrompt);

  console.log("\n=== STAGE 6: GEMINI REQUEST ===");
  const chatMessages = [
    { role: "user", parts: [{ text: systemPrompt }] },
    { role: "model", parts: [{ text: "Understood." }] },
    { role: "user", parts: [{ text: chatHistory[0].content }] }
  ];
  console.log("-> Exact prompt/content sent to Gemini:");
  console.log(JSON.stringify(chatMessages, null, 2));

  console.log("\n=== STAGE 7: GEMINI RESPONSE ===");
  const client = new GoogleGenAI({ apiKey });
  const response = await client.models.generateContentStream({
    model: "gemini-2.5-flash",
    contents: chatMessages as any
  });

  let fullResponse = "";
  let isFirst = true;
  for await (const chunk of response) {
    if (isFirst) {
      console.log("-> Raw response chunk before post-processing:");
      console.log(JSON.stringify(chunk, null, 2));
      isFirst = false;
    }
    if (chunk.text) fullResponse += chunk.text;
  }

  console.log("\n=== STAGE 8: FINAL WIDGET RESPONSE ===");
  console.log(fullResponse);
}

runTest().catch(console.error);
